"""Standalone RAG benchmark for the AI service (HTTP-level, black-box).

Measures four things against a live stack and writes raw artifacts so every
number can be re-checked by hand:

  latency  - sequential requests to POST /api/ai/similar-tickets with per-stage
             breakdown (Ollama embedding / Qdrant search / unaccounted overhead),
             plus a separate LLM-generation probe via SSE POST /api/ai/chat
             (time-to-first-token, generation tail, and out-of-band retrieval
             attribution so embed/search/generation costs are separable).
  load     - sustained concurrent traffic (default 10 -> 25 -> 50 workers) against
             POST /api/ai/similar-tickets and/or streamed /api/ai/chat via
             --load-endpoint, reporting achieved requests/sec (plus tokens/s for
             chat) and how latency shifts vs the sequential run.
  quality  - recall@k / precision@k (k = 1, 3, 5, 10) and MRR over an eval set of
             (query, expected_ticket_id) pairs. Pairs are generated by having the
             chat LLM paraphrase titles of real CLOSED tickets sampled from the
             index, then cached to results/eval_set.jsonl (edit freely; delete or
             pass --regen-eval-set to rebuild).
  scale    - current point count of the collection with a per-doc_type breakdown;
             every run appends to results/scale_history.csv so growth becomes
             visible across repeated runs; deltas vs the newest runs >=7 and
             >=30 days old are reported once history allows.

The service exposes no per-stage tracing, so stage timings are produced by
replaying each stage out-of-band against the very same backends the service
uses (same models, same filters, same scan size). Quality is scored with a
production-equivalent query: scan Settings.similar_scan points, filter
doc_type=ticket + status=closed, group by ticket keeping the best chunk score,
rank by score descending - exactly what SimilarityService does.

Usage (from services/ai-service/, venv activated):

  python bench/bench_rag.py                          # everything, defaults
  python bench/bench_rag.py --sections latency,scale # quick subset
  python bench/bench_rag.py --seq-requests 30 --load-duration 5 --eval-size 10
  python bench/bench_rag.py --reindex-tickets        # refresh index first (Admin)

Environment overrides: AI_BASE_URL, OLLAMA_URL, QDRANT_URL, BENCH_AUTH_TOKEN.
"""

