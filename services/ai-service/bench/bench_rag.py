async def stream_chat_once(
    client: httpx.AsyncClient, auth_header: str, message: str
) -> tuple[bool, int]:
    """Stream one /api/ai/chat answer; returns (completed_ok, token_event_count)."""
    try:
        async with client.stream(
            "POST",
            f"{AI_BASE_URL}/api/ai/chat",
            json={"message": message},
            headers={"Authorization": auth_header},
        ) as resp:
            if resp.status_code != 200:
                return False, 0
            current_event = ""
            tokens = 0
            async for line in resp.aiter_lines():
                if line.startswith("event:"):
                    current_event = line[len("event:"):].strip()
                elif line.startswith("data:") and current_event == "token":
                    tokens += 1
                elif current_event == "error":
                    return False, tokens
                elif current_event == "done":
                    return True, tokens
            return False, tokens
    except httpx.HTTPError:
        return False, 0


async def load_worker(
    client: httpx.AsyncClient,
    auth_header: str,
    deadline: float,
    start_signal: asyncio.Event,
    lock: asyncio.Lock,
    latencies: list[float],
    counters: dict,
    endpoint: str = "similar",
) -> None:
    await start_signal.wait()
    while time.perf_counter() < deadline:
        req_started = time.perf_counter()
        ok = False
        n_tokens = 0
        query = QUERY_POOL[random.randrange(len(QUERY_POOL))]
        try:
            if endpoint == "chat":
                ok, n_tokens = await stream_chat_once(client, auth_header, query)
            else:
                resp = await client.post(
                    f"{AI_BASE_URL}/api/ai/similar-tickets",
                    json={"query": query},
                    headers={"Authorization": auth_header},
                )
                ok = resp.status_code == 200
        except httpx.HTTPError:
            ok = False
        elapsed = (time.perf_counter() - req_started) * 1000.0
        async with lock:
            if ok:
                latencies.append(elapsed)
                counters["tokens"] = counters.get("tokens", 0) + n_tokens
            else:
                counters["errors"] += 1


async def run_load_test(
    client: httpx.AsyncClient,
    auth_header: str,
    levels: list[int],
    duration_s: float,
    endpoints: list[str],
) -> tuple[list[dict], list[dict]]:
    summary: list[dict] = []
    raw_rows: list[dict] = []

    for endpoint in endpoints:
        for level in levels:
            latencies: list[float] = []
            counters = {"errors": 0}
            lock = asyncio.Lock()
            start_signal = asyncio.Event()
            deadline = time.perf_counter() + duration_s

            tasks = [
                asyncio.create_task(
                    load_worker(
                        client, auth_header, deadline, start_signal, lock, latencies,
                        counters, endpoint,
                    )
                )
                for _ in range(level)
            ]
            start_signal.set()
            wall_started = time.perf_counter()
            await asyncio.gather(*tasks)
            wall_s = max(time.perf_counter() - wall_started, duration_s)
            errors = counters["errors"]

            rps = len(latencies) / wall_s if wall_s > 0 else float("nan")
            stats = latency_stats(latencies)
            row = {
                "endpoint": endpoint,
                "concurrency": level,
                "duration_s": round(wall_s, 2),
                "completed": len(latencies),
                "errors": errors,
                "achieved_rps": round(rps, 2),
                **stats,
            }
            if endpoint == "chat":
                tokens_per_s = counters.get("tokens", 0) / wall_s if wall_s > 0 else float("nan")
                row["tokens_per_s"] = round(tokens_per_s, 1)
            summary.append(row)
            raw_rows.extend(
                {"endpoint": endpoint, "concurrency": level, "latency_ms": round(value, 2)}
                for value in latencies
            )
            tok_cell = f" | {row.get('tokens_per_s', '-'):>7} tok/s" if endpoint == "chat" else ""
            print(
                f"  [{endpoint:>7}] concurrency {level:>3}: {rps:7.1f} req/s | p50 {stats['p50_ms']:>8.1f} ms"
                f" | p95 {stats['p95_ms']:>8.1f} ms | errors {errors}{tok_cell}"
            )

    print_table(
        f"LOAD TEST sustained ~{duration_s:.0f}s per level (endpoint e2e)",
        ["endpoint", "concurrency", "req/s", "completed", "errors", "tok/s",
         "p50 ms", "p95 ms", "p99 ms", "max ms"],
        [
            [
                row["endpoint"],
                row["concurrency"],
                row["achieved_rps"],
                row["completed"],
                row["errors"],
                row.get("tokens_per_s", "-"),
                row["p50_ms"],
                row["p95_ms"],
                row["p99_ms"],
                row["max_ms"],
            ]
            for row in summary
        ],
    )
    return summary, raw_rows


