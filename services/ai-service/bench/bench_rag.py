def percentile(sorted_values: list[float], p: float) -> float:
    """Linear-interpolation percentile on a pre-sorted list (numpy-style)."""
    if not sorted_values:
        return float("nan")
    if len(sorted_values) == 1:
        return sorted_values[0]
    rank = (p / 100.0) * (len(sorted_values) - 1)
    low = math.floor(rank)
    high = math.ceil(rank)
    frac = rank - low
    return sorted_values[low] * (1.0 - frac) + sorted_values[high] * frac


def latency_stats(samples_ms: list[float]) -> dict[str, float]:
    ordered = sorted(samples_ms)
    if not ordered:
        return {key: float("nan") for key in ("n", "mean_ms", "p50_ms", "p95_ms", "p99_ms", "max_ms")}
    return {
        "n": len(ordered),
        "mean_ms": round(statistics.fmean(ordered), 1),
        "p50_ms": round(percentile(ordered, 50), 1),
        "p95_ms": round(percentile(ordered, 95), 1),
        "p99_ms": round(percentile(ordered, 99), 1),
        "max_ms": round(ordered[-1], 1),
    }


def print_table(title: str, headers: list[str], rows: list[list]) -> None:
    def fmt(cell) -> str:
        if isinstance(cell, float):
            return f"{cell:.1f}" if math.isfinite(cell) else "-"
        return str(cell)

    rendered = [[fmt(cell) for cell in row] for row in rows]
    widths = [
        max([len(headers[i])] + [len(r[i]) for r in rendered]) for i in range(len(headers))
    ]
    print(f"\n{title}")
    print(" | ".join(h.ljust(widths[i]) for i, h in enumerate(headers)))
    print("-+-".join("-" * w for w in widths))
    for row in rendered:
        print(" | ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)))


def sanitize(obj):
    """Replace NaN/inf with None so the JSON artifact stays strictly valid."""
    if isinstance(obj, float):
        return obj if math.isfinite(obj) else None
    if isinstance(obj, dict):
        return {key: sanitize(value) for key, value in obj.items()}
    if isinstance(obj, list):
        return [sanitize(value) for value in obj]
    return obj


