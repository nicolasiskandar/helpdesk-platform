def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sections", default="latency,load,quality,scale",
                        help="comma-separated subset of latency,load,quality,scale")
    parser.add_argument("--seq-requests", type=int, default=SEQ_REQUESTS)
    parser.add_argument("--warmup", type=int, default=WARMUP_REQUESTS)
    parser.add_argument("--chat-requests", type=int, default=CHAT_PROBE_REQUESTS,
                        help="streamed /api/ai/chat probes for LLM-stage timing (0 skips)")
    parser.add_argument("--levels", type=str, default=",".join(map(str, CONCURRENCY_LEVELS)),
                        help="comma-separated concurrency levels, e.g. 10,25,50")
    parser.add_argument("--load-endpoint", type=str, default=",".join(LOAD_ENDPOINTS),
                        help="comma-separated subset of similar,chat the load section hits")
    parser.add_argument("--load-duration", type=float, default=LOAD_DURATION_SECONDS)
    parser.add_argument("--eval-size", type=int, default=EVAL_SET_SIZE)
    parser.add_argument("--eval-set", type=Path, default=EVAL_SET_PATH,
                        help="path to the (query, expected_ticket_id) pairs file")
    parser.add_argument("--regen-eval-set", action="store_true",
                        help="discard the cached eval_set.jsonl and regenerate pairs")
    parser.add_argument("--reindex-tickets", action="store_true",
                        help="POST /api/ai/reindex-tickets (Admin) before benchmarking")
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    return parser.parse_args()


async def main() -> None:
    args = parse_args()
    random.seed(args.seed)
    sections = {part.strip() for part in args.sections.split(",") if part.strip()}
    unknown = sections - {"latency", "load", "quality", "scale"}
    if unknown:
        raise SystemExit(f"unknown sections: {', '.join(sorted(unknown))}")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    run_stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")

    timeout = httpx.Timeout(REQUEST_TIMEOUT_SECONDS, connect=10.0)
    load_endpoints = [ep.strip() for ep in args.load_endpoint.split(",") if ep.strip()]
    unknown_endpoints = set(load_endpoints) - {"similar", "chat"}
    if unknown_endpoints:
        raise SystemExit(
            f"unknown load endpoints: {', '.join(sorted(unknown_endpoints))} (valid: similar, chat)"
        )
    async with httpx.AsyncClient(timeout=timeout, limits=httpx.Limits(max_connections=110)) as client:
        need_ai = bool(sections & {"latency", "load"})
        need_embed = need_ai or "quality" in sections
        need_chat = ("latency" in sections and args.chat_requests > 0) or (
            "load" in sections and "chat" in load_endpoints
        )
        await preflight(client, need_ai=need_ai, need_embed=need_embed, need_chat_model=need_chat)

        results: dict = {
            "started_at": utc_now_iso(),
            "config": {
                "ai_base_url": AI_BASE_URL,
                "ollama_url": OLLAMA_URL,
                "qdrant_url": QDRANT_URL,
                "collection": COLLECTION_NAME,
                "embedding_model": EMBEDDING_MODEL,
                "chat_model": CHAT_MODEL,
                "similar_scan": SIMILAR_SCAN,
                "seq_requests": args.seq_requests,
                "chat_requests": args.chat_requests,
                "levels": args.levels,
                "load_endpoints": load_endpoints,
                "load_duration_s": args.load_duration,
                "eval_size": args.eval_size,
                "seed": args.seed,
            },
        }

        auth_header = build_auth_header() if (need_ai or args.reindex_tickets) else ""
        token_preview = (auth_header[:20] + "...") if auth_header else "(not needed)"
        print(f"auth: {token_preview}")

        if args.reindex_tickets:
            print("reindexing tickets via /api/ai/reindex-tickets ...")
            resp = await client.post(
                f"{AI_BASE_URL}/api/ai/reindex-tickets",
                headers={"Authorization": auth_header},
                timeout=900.0,
            )
            if resp.status_code == 200:
                print(f"reindexed {resp.json()['indexed']} tickets")
            else:
                print(f"reindex failed (HTTP {resp.status_code}): {resp.text[:200]}")

        if "latency" in sections:
            seq_rows, seq_stats = await run_sequential_latency(
                client, auth_header, args.seq_requests, args.warmup
            )
            chat_rows, chat_stats = [], {}
            if args.chat_requests > 0:
                chat_rows, chat_stats = await run_chat_latency_probe(
                    client, auth_header, args.chat_requests
                )
            results["latency"] = {
                "sequential_summary": seq_stats,
                "chat_summary": chat_stats,
            }
            results["_raw_seq"] = seq_rows
            results["_raw_chat"] = chat_rows

        if "load" in sections:
            levels = [int(level) for level in args.levels.split(",") if level.strip()]
            load_summary, load_raw = await run_load_test(
                client, auth_header, levels, args.load_duration, load_endpoints
            )
            results["load"] = {"summary": load_summary}
            results["_raw_load"] = load_raw

        if "quality" in sections:
            quality_summary, quality_detail = await run_quality_eval(
                client, args.eval_size, args.regen_eval_set, args.eval_set
            )
            results["quality"] = quality_summary or {}
            results["_quality_detail"] = quality_detail

        if "scale" in sections:
            results["scale"] = await run_scale_check(client) or {}

        results["finished_at"] = utc_now_iso()

    json_path = RESULTS_DIR / f"run_{run_stamp}.json"
    json_path.write_text(json.dumps(sanitize(results), indent=2), encoding="utf-8")

    csv_specs = [
        ("_raw_seq", f"latency_raw_{run_stamp}.csv",
         ["index", "query", "e2e_ms", "embed_ms", "qdrant_ms", "overhead_ms", "num_results"]),
        ("_raw_chat", f"chat_raw_{run_stamp}.csv",
         ["ttft_ms", "total_ms", "tokens", "gen_tail_ms", "embed_ms", "qdrant_ms"]),
        ("_raw_load", f"load_raw_{run_stamp}.csv",
         ["endpoint", "concurrency", "latency_ms"]),
        ("_quality_detail", f"quality_detail_{run_stamp}.csv",
         ["query", "expected_reference_number", "rank",
          "top1_ref", "top1_score", "top2_ref", "top2_score", "top3_ref", "top3_score"]),
    ]
    written = [str(json_path)]
    for key, filename, fieldnames in csv_specs:
        rows = results.pop(key, [])
        if not rows:
            continue
        path = RESULTS_DIR / filename
        with path.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=fieldnames, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(rows)
        written.append(str(path))

    print("\nartifacts written:")
    for path in written:
        print(f"  {path}")


if __name__ == "__main__":
    asyncio.run(main())
