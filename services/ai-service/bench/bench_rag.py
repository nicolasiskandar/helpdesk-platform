def build_auth_header() -> str:
    """Return the Authorization header value: pasted token if provided, else mint one."""
    pasted = os.environ.get(AUTH_TOKEN_ENV, "").strip()
    if pasted:
        return pasted if pasted.lower().startswith("bearer ") else f"Bearer {pasted}"

    if not JWT_PRIVATE_KEY_PATH.exists():
        raise SystemExit(
            f"No bearer token available.\n"
            f"- Set {AUTH_TOKEN_ENV}=<jwt>, or\n"
            f"- generate signing keys with ./scripts.sh setup "
            f"(expected key at {JWT_PRIVATE_KEY_PATH})."
        )
    try:
        from jose import jwt as jose_jwt
    except ImportError as exc:
        raise SystemExit(
            "python-jose is required to mint tokens: pip install 'python-jose[cryptography]'"
        ) from exc

    claims = {
        "sub": JWT_SUBJECT,
        "email": f"{JWT_SUBJECT}@bench.local",
        "name": "Benchmark Runner",
        ROLE_CLAIM: "Admin",
        "iat": int(time.time()),
        "exp": int(time.time()) + JWT_TTL_SECONDS,
        "aud": JWT_AUDIENCE,
        "iss": JWT_ISSUER,
    }
    private_key = JWT_PRIVATE_KEY_PATH.read_text()
    return "Bearer " + jose_jwt.encode(claims, private_key, algorithm="RS256")


# ===================== backend stage calls =====================


async def embed_query(client: httpx.AsyncClient, query: str) -> tuple[list[float], float]:
    """Embed via Ollama exactly like EmbeddingClient does. Returns (vector, elapsed_ms)."""
    started = time.perf_counter()
    resp = await client.post(
        f"{OLLAMA_URL}/api/embeddings",
        json={"model": EMBEDDING_MODEL, "prompt": query, "keep_alive": 3600},
    )
    resp.raise_for_status()
    elapsed = (time.perf_counter() - started) * 1000.0
    return resp.json()["embedding"], elapsed


async def qdrant_ticket_search(
    client: httpx.AsyncClient, vector: list[float], limit: int
) -> tuple[list[dict], float]:
    """Closed-ticket search replicating VectorStore.search + SimilarityService filter."""
    started = time.perf_counter()
    resp = await client.post(
        f"{QDRANT_URL}/collections/{COLLECTION_NAME}/points/query",
        json={"query": vector, "limit": limit, "filter": TICKET_FILTER, "with_payload": True},
    )
    resp.raise_for_status()
    elapsed = (time.perf_counter() - started) * 1000.0
    return resp.json()["result"]["points"], elapsed


# ===================== preflight =====================


def normalize_model_name(name: str) -> str:
    return name if ":" in name else f"{name}:latest"


async def preflight(
    client: httpx.AsyncClient, *, need_ai: bool, need_embed: bool, need_chat_model: bool
) -> None:
    problems: list[str] = []

    if need_ai:
        try:
            resp = await client.get(f"{AI_BASE_URL}/health/ready")
            if resp.status_code != 200:
                problems.append(f"AI service {AI_BASE_URL} not ready (HTTP {resp.status_code})")
        except httpx.HTTPError as exc:
            problems.append(f"AI service unreachable at {AI_BASE_URL}: {exc!r}")

    try:
        if need_embed or need_chat_model:
            tags = (await client.get(f"{OLLAMA_URL}/api/tags")).json().get("models", [])
            present = {normalize_model_name(m.get("name", "")) for m in tags}
            wanted = ([EMBEDDING_MODEL] if need_embed else []) + (
                [CHAT_MODEL] if need_chat_model else []
            )
            for model in wanted:
                if normalize_model_name(model) not in present:
                    problems.append(
                        f"Ollama model '{model}' not pulled yet "
                        f"(ai-service pulls models on startup; check its logs)"
                    )
    except httpx.HTTPError as exc:
        problems.append(f"Ollama unreachable at {OLLAMA_URL}: {exc!r}")

    try:
        resp = await client.get(f"{QDRANT_URL}/collections/{COLLECTION_NAME}")
        if resp.status_code == 404:
            problems.append(
                f"Qdrant collection '{COLLECTION_NAME}' does not exist yet - create tickets, "
                f"then POST /api/ai/reindex-tickets (or use --reindex-tickets)"
            )
        elif resp.status_code != 200:
            problems.append(f"Qdrant collection lookup failed (HTTP {resp.status_code})")
    except httpx.HTTPError as exc:
        problems.append(f"Qdrant unreachable at {QDRANT_URL}: {exc!r}")

    if problems:
        raise SystemExit("Preflight failed:\n  - " + "\n  - ".join(problems))


# ===================== latency: sequential + stage breakdown =====================


async def run_sequential_latency(
    client: httpx.AsyncClient, auth_header: str, n_requests: int, warmup: int
) -> tuple[list[dict], dict[str, dict]]:
    rows: list[dict] = []
    errors = 0

    if warmup:
        print(f"warmup: discarding {warmup} requests (model load / connection setup)")
        for i in range(warmup):
            query = QUERY_POOL[i % len(QUERY_POOL)]
            try:
                vector, _ = await embed_query(client, query)
                await qdrant_ticket_search(client, vector, 1)
                await client.post(
                    f"{AI_BASE_URL}/api/ai/similar-tickets",
                    json={"query": query},
                    headers={"Authorization": auth_header},
                )
            except httpx.HTTPError:
                continue

    print(f"sequential: {n_requests} requests, each timed end-to-end plus out-of-band stages")
    for i in range(n_requests):
        query = QUERY_POOL[i % len(QUERY_POOL)]
        try:
            vector, embed_ms = await embed_query(client, query)
            _, search_ms = await qdrant_ticket_search(client, vector, SIMILAR_SCAN)
            req_started = time.perf_counter()
            resp = await client.post(
                f"{AI_BASE_URL}/api/ai/similar-tickets",
                json={"query": query},
                headers={"Authorization": auth_header},
            )
            e2e_ms = (time.perf_counter() - req_started) * 1000.0
        except httpx.HTTPError:
            errors += 1
            continue
        if resp.status_code != 200:
            errors += 1
            continue
        rows.append(
            {
                "index": i,
                "query": query,
                "e2e_ms": round(e2e_ms, 2),
                "embed_ms": round(embed_ms, 2),
                "qdrant_ms": round(search_ms, 2),
                "overhead_ms": round(max(0.0, e2e_ms - embed_ms - search_ms), 2),
                "num_results": len(resp.json()),
            }
        )
        if (i + 1) % 50 == 0 or i + 1 == n_requests:
            print(f"  {i + 1}/{n_requests} done ({errors} errors)")

    stages = {
        "endpoint e2e": [row["e2e_ms"] for row in rows],
        "embed (ollama)": [row["embed_ms"] for row in rows],
        "qdrant search": [row["qdrant_ms"] for row in rows],
        "overhead (app+net)": [row["overhead_ms"] for row in rows],
    }
    stats = {name: latency_stats(values) for name, values in stages.items()}
    print_table(
        f"LATENCY sequential ({len(rows)} ok, {errors} errors)",
        ["stage", "mean ms", "p50 ms", "p95 ms", "p99 ms", "max ms"],
        [
            [name] + [stat[key] for key in ("mean_ms", "p50_ms", "p95_ms", "p99_ms", "max_ms")]
            for name, stat in stats.items()
        ],
    )
    return rows, stats


# ===================== latency: LLM generation probe (RAG chat) =====================


async def chat_probe_once(
    client: httpx.AsyncClient, auth_header: str, question: str
) -> dict | None:
    """Stream one RAG chat answer; returns ttft/total/token counts, or None on failure."""
    started = time.perf_counter()
    ttft_ms: float | None = None
    tokens = 0
    try:
        async with client.stream(
            "POST",
            f"{AI_BASE_URL}/api/ai/chat",
            json={"message": question},
            headers={"Authorization": auth_header},
        ) as resp:
            if resp.status_code != 200:
                return None
            current_event = ""
            async for line in resp.aiter_lines():
                if line.startswith("event:"):
                    current_event = line[len("event:"):].strip()
                elif line.startswith("data:"):
                    if current_event == "token":
                        if ttft_ms is None:
                            ttft_ms = (time.perf_counter() - started) * 1000.0
                        tokens += 1
                    elif current_event == "error":
                        return None
                    elif current_event == "done":
                        break
    except httpx.HTTPError:
        return None
    if ttft_ms is None:
        return None
    total_ms = (time.perf_counter() - started) * 1000.0
    return {"ttft_ms": round(ttft_ms, 2), "total_ms": round(total_ms, 2), "tokens": tokens}


async def run_chat_latency_probe(
    client: httpx.AsyncClient, auth_header: str, n_requests: int
) -> tuple[list[dict], dict[str, dict]]:
    rows: list[dict] = []
    errors = 0
    print(f"chat generation probe: {n_requests} streamed answers ({CHAT_MODEL})")
    print("stage attribution: retrieval timed out-of-band (same replay trick as sequential)")
    for i in range(n_requests):
        question = QUERY_POOL[i % len(QUERY_POOL)]
        try:
            vector, embed_ms = await embed_query(client, question)
            _, search_ms = await qdrant_ticket_search(client, vector, SIMILAR_SCAN)
        except httpx.HTTPError:
            embed_ms = search_ms = None
        result = await chat_probe_once(client, auth_header, question)
        if result is None:
            errors += 1
        else:
            result["embed_ms"] = round(embed_ms, 2) if embed_ms is not None else None
            result["qdrant_ms"] = round(search_ms, 2) if search_ms is not None else None
            result["gen_tail_ms"] = round(result["total_ms"] - result["ttft_ms"], 2)
            rows.append(result)
        if (i + 1) % 10 == 0 or i + 1 == n_requests:
            print(f"  {i + 1}/{n_requests} done ({errors} errors)")

    stats = {
        "total stream time": latency_stats([row["total_ms"] for row in rows]),
        "time-to-first-token": latency_stats([row["ttft_ms"] for row in rows]),
        "generation tail (total-TTFT)": latency_stats([row["gen_tail_ms"] for row in rows]),
    }
    replay = [
        row["embed_ms"] + row["qdrant_ms"]
        for row in rows
        if row["embed_ms"] is not None and row["qdrant_ms"] is not None
    ]
    stats["retrieval replay (embed+qdrant)"] = latency_stats(replay)
    print_table(
        f"LLM GENERATION via /api/ai/chat ({len(rows)} ok)",
        ["metric", "mean ms", "p50 ms", "p95 ms", "p99 ms", "max ms"],
        [
            [name] + [stat[key] for key in ("mean_ms", "p50_ms", "p95_ms", "p99_ms", "max_ms")]
            for name, stat in stats.items()
        ],
    )
    totals = [row["total_ms"] for row in rows]
    if totals:
        gen_rate = sum(row["tokens"] for row in rows) / (sum(totals) / 1000.0)
        print(f"aggregate generation throughput: {gen_rate:.1f} tokens/s across all streams")
    return rows, stats


