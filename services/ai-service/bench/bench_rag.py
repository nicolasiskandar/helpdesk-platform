def growth_since(
    data: list[list[str]], now: datetime, days: int, current_total: int
) -> tuple[int, str] | None:
    """Delta vs the newest recorded run at least `days` old; None when history is too short."""
    cutoff = now - timedelta(days=days)
    snapshots: list[tuple[datetime, int]] = []
    for row in data:
        if len(row) < 2 or not row[1].isdigit():
            continue
        try:
            stamp = datetime.fromisoformat(row[0])
        except ValueError:
            continue
        if stamp <= cutoff:
            snapshots.append((stamp, int(row[1])))
    if not snapshots:
        return None
    stamp, past_total = max(snapshots, key=lambda entry: entry[0])
    return current_total - past_total, stamp.isoformat(timespec="seconds")


async def run_scale_check(client: httpx.AsyncClient) -> dict:
    info = (await client.get(f"{QDRANT_URL}/collections/{COLLECTION_NAME}")).json()["result"]
    total = info.get("points_count")

    breakdown: dict[str, int] = {}
    for doc_type in DOC_TYPES:
        resp = await client.post(
            f"{QDRANT_URL}/collections/{COLLECTION_NAME}/points/count",
            json={"filter": {"must": [{"key": "doc_type", "match": {"value": doc_type}}]}},
        )
        breakdown[doc_type] = int(resp.json()["result"]["count"])

    if total is None:
        total = sum(breakdown.values())

    print_table(
        f"INDEX SIZE collection '{COLLECTION_NAME}' (status: {info.get('status')})",
        ["metric", "points"],
        [["total", total]] + [[f"doc_type={name}", count] for name, count in breakdown.items()],
    )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    first_row: list[str] | None = None
    previous_row: list[str] | None = None
    data: list[list[str]] = []
    if SCALE_HISTORY_PATH.exists():
        with SCALE_HISTORY_PATH.open(newline="", encoding="utf-8") as handle:
            existing = [row for row in csv.reader(handle) if row]
        data = existing[1:] if existing else []
        if data:
            first_row, previous_row = data[0], data[-1]
            print_table(
                f"SCALE HISTORY ({len(data)} prior runs)",
                ["timestamp_utc", "total", "tickets", "comments", "kb"],
                [row[:5] for row in data[-10:]],
            )

    write_header = not SCALE_HISTORY_PATH.exists() or SCALE_HISTORY_PATH.stat().st_size == 0
    with SCALE_HISTORY_PATH.open("a", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        if write_header:
            writer.writerow(["timestamp_utc", "points_total", "tickets", "comments", "kb_articles"])
        writer.writerow([utc_now_iso(), total, breakdown["ticket"], breakdown["comment"], breakdown["kb"]])
    print(f"scale history appended to {SCALE_HISTORY_PATH}")

    deltas: dict[str, int | None] = {}
    if isinstance(total, int):
        if previous_row and previous_row[1].isdigit():
            print(f"growth vs previous run: {total - int(previous_row[1]):+d} points")
        if first_row and first_row is not previous_row and first_row[1].isdigit():
            print(f"growth since first recorded run ({first_row[0]}): {total - int(first_row[1]):+d} points")
        now = datetime.now(UTC)
        for days in (7, 30):
            outcome = growth_since(data, now, days, total)
            if outcome is None:
                deltas[f"points_{days}d_delta"] = None
                print(f"growth over last {days} days: no recorded run >= {days} days old yet")
            else:
                change, snapshot = outcome
                deltas[f"points_{days}d_delta"] = change
                print(f"growth over last {days} days: {change:+d} points (snapshot {snapshot})")
    return {"total": total, **breakdown, **deltas}


