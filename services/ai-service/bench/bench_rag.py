async def fetch_closed_tickets(client: httpx.AsyncClient, max_points: int) -> list[dict]:
    """Scroll closed-ticket points from Qdrant; returns one deduped summary per ticket."""
    tickets: list[dict] = []
    seen_ids: set[str] = set()
    offset = None
    while len(tickets) < max_points:
        body: dict = {
            "filter": TICKET_FILTER,
            "limit": min(250, max_points - len(tickets)),
            "with_payload": True,
        }
        if offset is not None:
            body["offset"] = offset
        resp = await client.post(
            f"{QDRANT_URL}/collections/{COLLECTION_NAME}/points/scroll", json=body
        )
        resp.raise_for_status()
        result = resp.json()["result"]
        for point in result.get("points", []):
            payload = point.get("payload") or {}
            doc_id = str(payload.get("doc_id") or "")
            title = str(payload.get("title") or "")
            if doc_id and title and doc_id not in seen_ids:
                seen_ids.add(doc_id)
                tickets.append(
                    {
                        "doc_id": doc_id,
                        "reference_number": payload.get("reference_number"),
                        "title": title,
                    }
                )
        offset = result.get("next_page_offset")
        if offset is None:
            break
    return tickets


async def generate_paraphrase(client: httpx.AsyncClient, title: str) -> tuple[str, str]:
    """Paraphrase a ticket title as an end-user query. Returns (query, source)."""
    prompt = (
        "Rewrite the following IT support ticket title as one informal sentence, phrased "
        "the way an end user would describe the problem when asking IT support for help. "
        "Use different wording than the original where possible. Reply with ONLY the "
        f"rewritten sentence.\n\nTicket title: \"{title}\""
    )
    try:
        resp = await client.post(
            f"{OLLAMA_URL}/api/generate",
            json={
                "model": CHAT_MODEL,
                "prompt": prompt,
                "stream": False,
                "options": {"temperature": 0.8, "num_predict": 60},
            },
            timeout=60.0,
        )
        resp.raise_for_status()
        text = str(resp.json().get("response", "")).strip().strip('"').strip("'")
        text = text.splitlines()[0].strip() if text else ""
        text = text[:250]
        if len(text) >= 8:
            return text, "llm_paraphrase"
    except httpx.HTTPError:
        pass
    return title, "title_fallback"


async def build_eval_set(
    client: httpx.AsyncClient, size: int, regen: bool, eval_path: Path
) -> tuple[list[dict], bool]:
    """Load cached eval pairs, or generate them from closed tickets in the index."""
    if eval_path.exists() and not regen:
        pairs = [json.loads(line) for line in eval_path.read_text().splitlines() if line.strip()]
        print(f"eval set: loaded {len(pairs)} cached pairs from {eval_path}")
        return pairs, False

    all_tickets = await fetch_closed_tickets(client, max_points=5000)
    if not all_tickets:
        raise SystemExit(
            "No CLOSED tickets found in the index - quality eval needs closed tickets. "
            "Create tickets, close some, then POST /api/ai/reindex-tickets."
        )
    if len(all_tickets) < size:
        print(f"warning: only {len(all_tickets)} closed tickets available, reducing eval size")
        size = len(all_tickets)
    sampled = random.sample(all_tickets, size)

    print(f"eval set: generating {size} paraphrased queries via {CHAT_MODEL}")
    pairs: list[dict] = []
    for i, ticket in enumerate(sampled):
        query, source = await generate_paraphrase(client, ticket["title"])
        pairs.append(
            {
                "query": query,
                "expected_doc_id": ticket["doc_id"],
                "expected_reference_number": ticket["reference_number"],
                "source_title": ticket["title"],
                "source": source,
            }
        )
        if (i + 1) % 10 == 0 or i + 1 == size:
            print(f"  {i + 1}/{size} generated")

    eval_path.parent.mkdir(parents=True, exist_ok=True)
    eval_path.write_text("".join(json.dumps(pair) + "\n" for pair in pairs), encoding="utf-8")
    print(f"eval set: cached {len(pairs)} pairs to {eval_path} (edit freely, rerun to rescore)")
    return pairs, True


async def run_quality_eval(
    client: httpx.AsyncClient, size: int, regen: bool, eval_path: Path
) -> tuple[dict | None, list[dict]]:
    pairs, generated = await build_eval_set(client, size, regen, eval_path)
    if not pairs:
        return None, []

    detail: list[dict] = []
    ranks: list[int | None] = []
    for i, pair in enumerate(pairs):
        try:
            vector, _ = await embed_query(client, pair["query"])
            points, _ = await qdrant_ticket_search(client, vector, SIMILAR_SCAN)
        except httpx.HTTPError as exc:
            print(f"  pair {i + 1}: backend error ({exc!r}), skipping")
            continue

        best_by_doc: dict[str, float] = {}
        titles_by_doc: dict[str, str] = {}
        for point in points:
            payload = point.get("payload") or {}
            doc_id = str(payload.get("doc_id") or "")
            if not doc_id:
                continue
            score = float(point.get("score") or 0.0)
            if doc_id not in best_by_doc or score > best_by_doc[doc_id]:
                best_by_doc[doc_id] = score
                titles_by_doc[doc_id] = str(payload.get("title") or "")
        ranked = sorted(best_by_doc, key=lambda doc: best_by_doc[doc], reverse=True)

        expected = pair["expected_doc_id"]
        rank = ranked.index(expected) + 1 if expected in ranked else None
        ranks.append(rank)
        top_entries = [
            {"ref": titles_by_doc[doc][:80], "score": round(best_by_doc[doc], 4)}
            for doc in ranked[:3]
        ]
        flat_top = {
            f"top{i}_{field}": value
            for i, entry in enumerate(top_entries, start=1)
            for field, value in entry.items()
        }
        detail.append(
            {
                "query": pair["query"],
                "expected_reference_number": pair.get("expected_reference_number"),
                "rank": rank,
                "top3": top_entries,
                **flat_top,
            }
        )
        if (i + 1) % 20 == 0 or i + 1 == len(pairs):
            print(f"  scored {i + 1}/{len(pairs)}")

    total = len(ranks)
    if total == 0:
        print("quality eval: no pairs could be scored")
        return None, []

    table_rows = []
    metrics: dict = {}
    for k in K_VALUES:
        hits = sum(1 for rank in ranks if rank is not None and rank <= k)
        recall = hits / total
        precision_at_k = hits / (total * k)
        metrics[f"recall@{k}"] = round(recall, 4)
        metrics[f"precision@{k}"] = round(precision_at_k, 4)
        table_rows.append([k, f"{recall * 100:.1f}% ({hits}/{total})", f"{precision_at_k * 100:.1f}%"])
    mrr = sum((1.0 / rank if rank else 0.0) for rank in ranks) / total
    metrics["mrr"] = round(mrr, 4)

    print_table(
        f"RETRIEVAL QUALITY ({total} pairs, single relevant ticket each: recall@k == hit-rate@k)",
        ["k", "recall@k (hit rate)", "precision@k"],
        table_rows,
    )
    print(f"Mean Reciprocal Rank (MRR): {mrr:.3f}")
    misses = [item for item in detail if item["rank"] is None]
    if misses:
        print(f"misses (expected ticket not in top-{max(K_VALUES)}): {len(misses)}/{total}")
        for item in misses[:5]:
            print(
                f"  expected {item['expected_reference_number']} for: {item['query'][:70]!r}"
            )

    return {"pairs": total, "generated_now": generated, **metrics}, detail


